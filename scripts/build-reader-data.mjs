import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';

// Keep the authored case studies as the source of truth. The homepage only needs
// catalogue data; an opened reader needs one project's narrative and process.
export async function buildReaderData(publicRoot) {
  const normal = path.join(publicRoot, 'normal-portfolio');
  const load = file => import(pathToFileURL(path.join(normal, file)).href);
  const [additions, {CASE_STORIES}, {PROJECT_PROCESS}] = await Promise.all([
    load('normal-projects.js'), load('case-stories.js'), load('process-data.js'),
  ]);
  const directory = path.join(normal, 'reader-data');
  await fs.mkdir(directory, {recursive: true});
  const urls = {};
  for (const [id, story] of Object.entries({...CASE_STORIES, ...additions.NORMAL_PROJECT_STORIES})) {
    const process = additions.NORMAL_PROJECT_PROCESS[id] ?? PROJECT_PROCESS[id];
    const json = JSON.stringify({story, process});
    const version = createHash('sha256').update(json).digest('hex').slice(0, 12);
    await fs.writeFile(path.join(directory, id + '.json'), json);
    urls[id] = './reader-data/' + id + '.json?v=' + version;
  }
  const {NORMAL_PROJECTS, NORMAL_PROJECT_CONTEXT, NORMAL_PROJECT_CATEGORIES, NORMAL_PROJECT_ARTIFACTS, PROJECT_COVERS} = additions;
  const catalogue = {NORMAL_PROJECTS, NORMAL_PROJECT_CONTEXT, NORMAL_PROJECT_CATEGORIES, NORMAL_PROJECT_ARTIFACTS, PROJECT_COVERS, READER_URLS: urls};
  const lines = Object.entries(catalogue).map(([name, data]) => 'export const ' + name + ' = ' + JSON.stringify(data, null, 2) + ';');
  await fs.writeFile(path.join(normal, 'project-catalogue.js'), '// Generated by scripts/build-reader-data.mjs.\n' + lines.join('\n') + '\n');
}
